/**
 * تب «معاملات» — ۱۰۰٪ خودکار و خوانا، بدون نیاز به نوشتن دستی:
 * هر معامله با خلاصه ساده (سود/زیان، مدت، وضعیت حد ضرر و تحلیل خودکار علت ورود) نمایش داده می‌شود.
 * ویرایش تگ یا یادداشت دستی فقط در صورت تمایل داخل بخش بازشوندهٔ «ویرایش دلخواه» است.
 */
import { useEffect, useMemo, useState } from 'react';
import { ChevronDown, ShieldAlert, ShieldCheck, Sparkles, TrendingDown, TrendingUp } from 'lucide-react';
import { Surface } from '@/shared/components/ui/GlassCard';
import { Badge } from '@/shared/components/ui/Badge';
import { Button } from '@/shared/components/ui/Button';
import { ChipGroup } from '@/shared/components/ui/SegmentedControl';
import { Field, Select } from '@/shared/components/ui/Input';
import { cn } from '@/shared/lib/cn';
import type { ClassifiedTrade, JournalSettings, TradeNote, TradePlan } from '../domain/types';
import { VENUE_FA } from '../domain/types';
import { saveNote } from '../data/journalStore';
import { duration, fa, faDateTime, pnlTone, TagPicker, usd } from './parts';
import { AmountText } from '@/shared/components/ui/FinancialValue';

type Filter = 'all' | 'open' | 'wins' | 'losses' | 'directional' | 'neutral';

function TradeCard({
  t,
  note,
  plan,
  auto,
  settings
}: {
  t: ClassifiedTrade;
  note: TradeNote | undefined;
  plan: TradePlan | undefined;
  auto: TradePlan | undefined;
  settings: JournalSettings;
}) {
  const [open, setOpen] = useState(false);
  const [draft, setDraft] = useState(note?.note ?? '');
  const [err, setErr] = useState<string | null>(null);
  useEffect(() => {
    setDraft(note?.note ?? '');
  }, [note?.note]);

  const save = (patch: Partial<TradeNote>) =>
    void saveNote(note, t.id, { ...patch, autoGenerated: false }, t.open).catch(() => setErr('ذخیره نشد'));

  const isLong = t.direction === 'long';
  const isWin = !t.open && t.netPnl > 0;
  const isLoss = !t.open && t.netPnl < 0;
  const whyTags = note?.whyTags ?? [];
  const isAuto = !!note?.autoGenerated;

  return (
    <Surface
      className={cn(
        'relative overflow-hidden p-4 transition-all duration-150 hover:border-accent/35 hover:shadow-sm',
        isWin && 'border-s-[3px] border-s-gain',
        isLoss && 'border-s-[3px] border-s-negative',
        t.open && 'border-s-[3px] border-s-warn'
      )}
    >
      {/* ردیف بالا: نماد، جهت، بج‌ها و سود/زیان */}
      <div className="flex flex-wrap items-center gap-2.5">
        <span
          className={cn(
            'inline-flex h-9 w-9 shrink-0 items-center justify-center rounded-xl',
            isLong ? 'bg-gain/12 text-gain-text' : 'bg-negative/12 text-negative'
          )}
        >
          {isLong ? <TrendingUp className="h-4.5 w-4.5" aria-hidden /> : <TrendingDown className="h-4.5 w-4.5" aria-hidden />}
        </span>

        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-1.5">
            <span className="text-sm font-extrabold text-ink" dir="ltr">
              {t.symbol}
            </span>
            <Badge tone={isLong ? 'gain' : 'loss'}>{isLong ? 'خرید (لانگ)' : 'فروش (شورت)'}</Badge>
            <Badge tone={t.book === 'neutral' ? 'info' : 'neutral'}>{t.book === 'neutral' ? 'فاندینگ / خنثی' : 'معامله معمولی'}</Badge>
            {t.open && <Badge tone="warn">باز</Badge>}
            {plan && <Badge tone="gain">با برنامه</Badge>}
            {!plan && auto?.auto?.stopSource === 'exchange' && (
              <Badge tone="gain">
                <ShieldCheck />
                حد ضرر {fa(auto.stop, 5)}
              </Badge>
            )}
            {!plan && auto?.auto?.stopSource === 'none' && (
              <Badge tone="loss">
                <ShieldAlert />
                بدون حد ضرر
              </Badge>
            )}
          </div>
          <p className="mt-1 text-xs text-muted">
            {VENUE_FA[t.venue]} · {faDateTime(t.openTime)}
            {t.closeTime ? ` · مدت ${duration(t.closeTime - t.openTime)}` : ''} · حجم {usd(t.maxNotional)}
          </p>
        </div>

        <div className="ms-auto text-end">
          <span className={cn('num-ltr block text-base font-extrabold', t.open ? 'text-warn' : pnlTone(t.netPnl))}>
            <AmountText text={t.open ? 'باز' : usd(t.netPnl, true)} />
          </span>
          {(t.fees !== null || t.funding !== null) && (
            <span className="mt-0.5 block text-[11px] text-subtle">
              {t.fees !== null ? `کارمزد ${usd(t.fees)}` : ''}
              {t.fees !== null && t.funding !== null ? ' · ' : ''}
              {t.funding !== null ? `فاندینگ ${usd(t.funding, true)}` : ''}
            </span>
          )}
        </div>
      </div>

      {/* خلاصه خودکار به زبان ساده — هیچ تایپی لازم نیست */}
      <div className="mt-3 rounded-xl border border-divider/70 bg-surface-2/45 px-3 py-2.5 text-xs">
        <div className="flex flex-wrap items-center gap-1.5">
          <Sparkles className="h-3.5 w-3.5 shrink-0 text-accent" aria-hidden />
          <span className="font-semibold text-ink">چرا وارد شدم؟</span>
          {whyTags.length > 0 ? (
            whyTags.map((tag) => (
              <span key={tag} className="rounded-full bg-card px-2 py-0.5 text-[11px] font-medium text-ink ring-1 ring-divider/80">
                {tag}
              </span>
            ))
          ) : (
            <span className="text-muted">تحلیل خودکار از داده معامله</span>
          )}
          {note?.followedRules !== null && note?.followedRules !== undefined && (
            <Badge tone={note.followedRules ? 'gain' : 'loss'} className="ms-auto">
              {note.followedRules ? 'طبق قانون بود' : 'خلاف قانون بود'}
            </Badge>
          )}
        </div>
        {note?.note && !open && <p className="mt-1.5 leading-6 text-muted">{note.note}</p>}
        <div className="mt-2 flex flex-wrap items-center justify-between gap-2 border-t border-divider/60 pt-2 text-[11px] text-subtle">
          <span>
            {t.entryPx ? `ورود ${fa(t.entryPx, 4)}` : ''}
            {t.exitPx && !t.open ? ` ← خروج ${fa(t.exitPx, 4)}` : ''}
            {isAuto ? ' · ثبت‌شده خودکار' : ''}
          </span>
          <button
            type="button"
            onClick={() => setOpen((o) => !o)}
            className="inline-flex items-center gap-1 font-semibold text-accent hover:underline"
          >
            <span>{open ? 'بستن ویرایش' : 'ویرایش دلخواه (اختیاری)'}</span>
            <ChevronDown className={cn('h-3.5 w-3.5 transition-transform', open && 'rotate-180')} aria-hidden />
          </button>
        </div>
      </div>

      {/* بخش ویرایش اختیاری — کاملاً جمع‌شده تا صفحه تمیز و بدون فرم تایپ بماند */}
      {open && (
        <div className="mt-3 space-y-3 rounded-xl border border-divider/80 bg-card p-3.5">
          <div>
            <p className="mb-1.5 text-xs font-semibold text-ink">تغییر دلیل ورود</p>
            <TagPicker label="چرا وارد شدم" tags={settings.whyTags} value={whyTags} onChange={(v) => save({ whyTags: v })} />
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <span className="text-xs font-semibold text-ink">طبق قوانینت بود؟</span>
            {(
              [
                [true, 'بله'],
                [false, 'خیر'],
                [null, 'نامشخص']
              ] as const
            ).map(([v, label]) => (
              <button
                key={label}
                type="button"
                aria-pressed={note?.followedRules === v}
                onClick={() => save({ followedRules: v })}
                className={cn(
                  'rounded-full border px-2.5 py-1 text-xs font-medium transition-colors',
                  note?.followedRules === v
                    ? v === true
                      ? 'border-gain bg-gain/10 text-positive'
                      : v === false
                        ? 'border-negative bg-negative/10 text-negative'
                        : 'border-accent bg-accent-soft text-accent'
                    : 'border-divider text-muted hover:text-ink'
                )}
              >
                {label}
              </button>
            ))}
          </div>
          <div>
            <p className="mb-1 text-xs font-semibold text-negative">اشتباه‌ها</p>
            <TagPicker label="اشتباه‌ها" tone="loss" tags={settings.mistakeTags} value={note?.mistakeTags ?? []} onChange={(v) => save({ mistakeTags: v })} />
          </div>
          <div>
            <p className="mb-1 text-xs font-semibold text-positive">کار درست</p>
            <TagPicker label="کار درست" tone="gain" tags={settings.goodTags} value={note?.goodTags ?? []} onChange={(v) => save({ goodTags: v })} />
          </div>
          <Field label="یادداشت شخصی (اختیاری)">
            <textarea
              className="min-h-16 w-full rounded-xl border border-divider bg-surface-2/40 p-2.5 text-sm"
              value={draft}
              onChange={(e) => setDraft(e.target.value)}
              onBlur={() => draft !== (note?.note ?? '') && save({ note: draft.slice(0, 2000) })}
            />
          </Field>
          <div className="flex flex-wrap items-center gap-2 text-xs">
            <span className="text-muted">نوع حساب: {t.bookReason}</span>
            <Select className="w-auto" value={note?.book ?? ''} onChange={(e) => save({ book: (e.target.value || undefined) as TradeNote['book'] })}>
              <option value="">تشخیص خودکار</option>
              <option value="directional">معامله معمولی</option>
              <option value="neutral">فاندینگ / خنثی</option>
            </Select>
          </div>
        </div>
      )}
      {err && <p className="mt-2 text-xs text-negative">{err}</p>}
    </Surface>
  );
}

export function TradesTab({
  trades,
  notes,
  links,
  auto,
  settings
}: {
  trades: ClassifiedTrade[];
  notes: Map<string, TradeNote>;
  links: Map<string, TradePlan>;
  auto: Map<string, TradePlan>;
  settings: JournalSettings;
}) {
  const [filter, setFilter] = useState<Filter>('all');
  const [limit, setLimit] = useState(30);
  const list = useMemo(() => {
    const base = [...trades].sort((a, b) => Number(b.open) - Number(a.open) || (b.closeTime ?? b.openTime) - (a.closeTime ?? a.openTime));
    return base.filter((t) => {
      if (filter === 'all') return true;
      if (filter === 'open') return t.open;
      if (filter === 'wins') return !t.open && t.netPnl > 0;
      if (filter === 'losses') return !t.open && t.netPnl < 0;
      return t.book === filter;
    });
  }, [trades, filter]);

  return (
    <div className="space-y-4">
      <ChipGroup
        label="فیلتر معاملات"
        bleed
        value={filter}
        onChange={setFilter}
        options={[
          { value: 'all', label: 'همه', badge: trades.length },
          { value: 'open', label: 'باز', badge: trades.filter((t) => t.open).length || undefined },
          { value: 'wins', label: 'سودده', badge: trades.filter((t) => !t.open && t.netPnl > 0).length || undefined },
          { value: 'losses', label: 'ضررده', badge: trades.filter((t) => !t.open && t.netPnl < 0).length || undefined },
          { value: 'directional', label: 'معامله معمولی' },
          { value: 'neutral', label: 'فاندینگ / خنثی' }
        ]}
      />
      {!list.length ? (
        <Surface className="p-6 text-center text-sm text-muted">معامله‌ای در این دسته پیدا نشد.</Surface>
      ) : (
        <div className="space-y-3">
          {list.slice(0, limit).map((t) => (
            <TradeCard key={t.id} t={t} note={notes.get(t.id)} plan={links.get(t.id)} auto={auto.get(t.id)} settings={settings} />
          ))}
        </div>
      )}
      {list.length > limit && (
        <Button variant="outline" onClick={() => setLimit((l) => l + 30)}>
          نمایش ۳۰ معاملهٔ بیشتر ({fa(list.length - limit)} باقی‌مانده)
        </Button>
      )}
    </div>
  );
}
