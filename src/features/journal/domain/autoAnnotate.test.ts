import { describe, expect, it } from 'vitest';
import { DEFAULT_SETTINGS } from './defaults';
import { buildAutoCritiqueLoop, buildEffectiveNotes, inferAutoTradeNote } from './autoAnnotate';
import { buildSuggestedPlanLevels, dailyAtr } from './autoPlan';
import { buildLocalReviewSuggestion } from './reviewAssist';
import { runJournal } from './audit';
import type { ClassifiedTrade, TradeNote, TradePlan } from './types';
import { emptyOutlook } from './plan';
import { analyzeReviewWithMeta, buildDeterministicReview } from '../../../../api/_assistant';

const DAY = 86_400_000;
const NOW = Date.UTC(2026, 10, 19, 10, 0, 0);

function makeTrade(overrides: Partial<ClassifiedTrade> = {}): ClassifiedTrade {
  return {
    id: 'hl:0x1|BTC|1',
    account: 'hyperliquid:0x1',
    venue: 'hyperliquid',
    symbol: 'BTC',
    base: 'BTC',
    direction: 'long',
    openTime: NOW - 4 * 3_600_000,
    closeTime: NOW - 3_600_000,
    open: false,
    truncated: false,
    entryPx: 90_000,
    exitPx: 91_500,
    maxSize: 0.1,
    maxNotional: 9_000,
    volume: 18_000,
    grossPnl: 150,
    fees: 5,
    funding: 0,
    netPnl: 145,
    fills: 2,
    liquidated: false,
    book: 'directional',
    bookReason: 'حساب جهت‌دار',
    hedgeGroup: null,
    ...overrides
  };
}

describe('خودکارسازی یادداشت «چرا وارد شدم؟» و قوانین معامله', () => {
  it('وقتی کاربر یادداشت نزده، تگ «چرا وارد شدم؟»، یادداشت فارسی و وضعیت قوانین را خودکار پر می‌کند', () => {
    const trade = makeTrade();
    const plan: TradePlan = {
      id: 'auto:1',
      createdAt: trade.openTime,
      updatedAt: trade.closeTime!,
      symbol: 'BTC',
      direction: 'long',
      account: trade.account,
      entry: 90_000,
      stop: 89_000,
      target: 92_000,
      size: 0.1,
      leverage: null,
      setupTags: [],
      entryWhy: '',
      stopWhy: '',
      targetWhy: '',
      confluences: [],
      reasonsAgainst: [],
      outlook: { ...emptyOutlook(), dailyBias: 'bullish', weeklyBias: 'bullish', env: 'trend', proTrend: 'y' },
      status: 'taken',
      linkedTradeId: trade.id,
      validHours: 0,
      notes: '',
      source: 'auto',
      auto: { stopSource: 'exchange', unreadableWhy: null, stopLateMin: null, finalStop: 89_000, stopMoved: 'none', outlookAuto: true }
    };

    const note = inferAutoTradeNote({
      trade,
      prevTrade: null,
      plan,
      settings: DEFAULT_SETTINGS,
      accountSize: 20_000
    });

    expect(note.autoGenerated).toBe(true);
    expect(note.whyTags).toContain('هم‌جهت با روند');
    expect(note.followedRules).toBe(true);
    expect(note.goodTags).toContain('رعایت استاپ');
    expect(note.note).toContain('BTC');
  });

  it('یادداشت دستی کاربر را هرگز بازنویسی نمی‌کند', () => {
    const trade = makeTrade();
    const manual: TradeNote = {
      tradeId: trade.id,
      whyTags: ['شکست سقف'],
      whyTaggedBeforeClose: true,
      mistakeTags: [],
      goodTags: ['صبر برای تأیید'],
      note: 'یادداشت دستی من',
      followedRules: true,
      updatedAt: NOW
    };
    const merged = buildEffectiveNotes({
      trades: [trade],
      manualNotes: new Map([[trade.id, manual]]),
      plans: new Map(),
      settings: DEFAULT_SETTINGS,
      accountSize: 20_000
    });

    expect(merged.get(trade.id)?.whyTags).toEqual(['شکست سقف']);
    expect(merged.get(trade.id)?.note).toBe('یادداشت دستی من');
    expect(merged.get(trade.id)?.autoGenerated).toBeFalsy();
  });
});

describe('برنامهٔ خودکار معامله با ATR14 و لوپ نقد کمّی', () => {
  it('ATR14 و سطوح پیشنهادی استاپ/هدف ۲R را از کندل‌های روزانه می‌سازد', () => {
    const candles = Array.from({ length: 20 }, (_, i) => ({
      t: NOW - (20 - i) * DAY,
      o: 90_000,
      h: 91_000,
      l: 89_000,
      c: 90_000
    }));
    const atr = dailyAtr(candles, NOW);
    expect(atr).toBe(2000);

    const sug = buildSuggestedPlanLevels({
      entry: 90_000,
      direction: 'long',
      outlook: { ...emptyOutlook(), proTrend: 'y', env: 'trend' },
      atr
    });
    expect(sug?.source).toBe('atr');
    expect(sug?.stop).toBe(87_000);
    expect(sug?.target).toBe(96_000);
  });

  it('لوپ نقد خودکار ۳ مرحله‌ای از حسابرسی می‌سازد و تعهد قابل‌سنجش تولید می‌کند', () => {
    const trades = [
      makeTrade({ id: 't1', netPnl: -300, grossPnl: -295, openTime: NOW - 5 * DAY, closeTime: NOW - 5 * DAY + 3_600_000 }),
      makeTrade({ id: 't2', netPnl: 120, grossPnl: 125, openTime: NOW - 4 * DAY, closeTime: NOW - 4 * DAY + 3_600_000 })
    ];
    const audit = runJournal({
      trades,
      fills: [],
      funding: [],
      accounts: [{ key: 'hyperliquid:0x1', venue: 'hyperliquid', label: 'HL', address: '0x1' }],
      notes: new Map(),
      plans: [],
      settings: DEFAULT_SETTINGS,
      accountSize: 10_000,
      platformDaily: new Map(),
      from: 0,
      tz: 'Asia/Tehran',
      sourceNotes: [],
      now: NOW
    });

    const loop = buildAutoCritiqueLoop(audit.directional, DEFAULT_SETTINGS, NOW);
    expect(loop.active).toBe(true);
    expect(loop.steps).toHaveLength(3);
    expect(loop.proposedCommitments.length).toBeGreaterThan(0);
  });
});

describe('مرور هفتگی بدون خطا (پشتیبان سرور و کلاینت)', () => {
  const samplePayload = {
    week: '2026-W47',
    stats: { trades: 2, netPnlUsd: -150, winRatePct: 50, offRulesCount: 1 },
    trades: [
      { symbol: 'BTC', direction: 'long', netPnlUsd: -250, stop: 'none', stopMoved: null, liquidated: false, riskPct: null },
      { symbol: 'ETH', direction: 'short', netPnlUsd: 100, stop: 'exchange', stopMoved: 'none', liquidated: false, riskPct: 0.8 }
    ],
    previousCommitments: [],
    mistakeTags: DEFAULT_SETTINGS.mistakeTags,
    goodTags: DEFAULT_SETTINGS.goodTags,
    whyTags: DEFAULT_SETTINGS.whyTags,
    questions: DEFAULT_SETTINGS.questions,
    maxRiskPct: 1,
    spot: null
  };

  it('حتی در نبود کلید Gemini، analyzeReviewWithMeta خطا نمی‌دهد و مرور کامل برمی‌گرداند', async () => {
    const oldKeys = {
      GEMINI_API_KEY: process.env.GEMINI_API_KEY,
      GEMINI_API_KEY_REVIEW: process.env.GEMINI_API_KEY_REVIEW,
      GEMINI_API_KEY_CHAT: process.env.GEMINI_API_KEY_CHAT,
      GEMINI_API_KEY_PERFORMANCE: process.env.GEMINI_API_KEY_PERFORMANCE,
      GEMINI_API_KEY_TOOLS: process.env.GEMINI_API_KEY_TOOLS
    };
    delete process.env.GEMINI_API_KEY;
    delete process.env.GEMINI_API_KEY_REVIEW;
    delete process.env.GEMINI_API_KEY_CHAT;
    delete process.env.GEMINI_API_KEY_PERFORMANCE;
    delete process.env.GEMINI_API_KEY_TOOLS;

    try {
      const res = await analyzeReviewWithMeta(samplePayload);
      expect(res.provider).toBe('fallback');
      expect(res.review.summary.length).toBeGreaterThan(20);
      expect(res.review.commitments.length).toBeGreaterThan(0);
    } finally {
      for (const [k, v] of Object.entries(oldKeys)) {
        if (v !== undefined) process.env[k] = v;
      }
    }
  });

  it('پشتیبان سمت کلاینت و سرور هر دو ساختار معتبر برمی‌گردانند', () => {
    const serverFallback = buildDeterministicReview(samplePayload);
    const clientFallback = buildLocalReviewSuggestion(samplePayload);
    expect(serverFallback.summary).toContain('BTC');
    expect(clientFallback.summary).toContain('2026-W47');
    expect(clientFallback.commitments.length).toBeGreaterThan(0);
  });
});
